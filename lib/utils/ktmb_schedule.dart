import 'dart:convert';

import 'package:flutter/foundation.dart';
import 'package:flutter/services.dart' show rootBundle;

/// One scheduled train between two stations on a given date.
class TrainDeparture {
  final String routeId;
  final String routeLabel;

  /// Departure time as minutes after midnight (0..1439).
  final int departMinutes;

  /// Journey time in minutes.
  final int durationMinutes;

  const TrainDeparture({
    required this.routeId,
    required this.routeLabel,
    required this.departMinutes,
    required this.durationMinutes,
  });

  int get arriveMinutes => (departMinutes + durationMinutes) % 1440;

  /// How many calendar days later the train arrives (overnight services).
  int get arriveDayOffset => (departMinutes + durationMinutes) ~/ 1440;
}

/// Real KTMB timetable (ETS, intercity, shuttle and Komuter) bundled with the
/// app from the official GTFS feed published by data.gov.my.
///
/// The asset is generated by `tool/build_ktmb_schedule.py`; re-run that script
/// when KTMB publishes a new timetable (see [validTo]).
///
/// Everything here works offline and needs no API key.
class KtmbSchedule {
  KtmbSchedule.fromJson(Map<String, dynamic> json)
    : validFrom = json['validFrom'] as String? ?? '',
      validTo = json['validTo'] as String? ?? '',
      _stops = List<String>.from(json['stops'] as List),
      _services = (json['services'] as Map).map(
        (k, v) => MapEntry(k as String, List<int>.from(v as List)),
      ),
      _exceptions = {
        for (final e in json['exceptions'] as List)
          '${(e as List)[0]}|${e[1]}': e[2] as int,
      },
      _trips = [
        for (final t in json['trips'] as List)
          _Trip(
            routeId: (t as Map)['r'] as String,
            serviceId: t['s'] as String,
            stops: [
              for (final s in t['t'] as List)
                _StopTime(
                  (s as List)[0] as int,
                  s[1] as int,
                  s[2] as int,
                ),
            ],
          ),
      ] {
    _stopIndexByName = {
      for (var i = 0; i < _stops.length; i++) _normalize(_stops[i]): i,
    };
  }

  final String validFrom;
  final String validTo;
  final List<String> _stops;
  final Map<String, List<int>> _services;
  final Map<String, int> _exceptions;
  final List<_Trip> _trips;
  late final Map<String, int> _stopIndexByName;

  static KtmbSchedule? _instance;

  /// The loaded schedule, or null if [load] has not finished / failed.
  /// Callers must treat null as "no schedule data" and fall back.
  static KtmbSchedule? get instance => _instance;

  /// Loads the bundled asset once. Safe to call repeatedly; never throws.
  static Future<KtmbSchedule?> load() async {
    if (_instance != null) return _instance;
    try {
      final raw = await rootBundle.loadString('assets/ktmb_schedule.json');
      _instance = KtmbSchedule.fromJson(jsonDecode(raw) as Map<String, dynamic>);
    } catch (e) {
      debugPrint('KtmbSchedule: could not load timetable asset: $e');
    }
    return _instance;
  }

  // ───────────────────────── Station matching ─────────────────────────

  static const Set<String> _noiseWords = {
    'railway',
    'station',
    'stesen',
    'ktm',
    'ktmb',
    'komuter',
    'ets',
    'stn',
    'terminal',
  };

  /// Alternate spellings people / autocomplete use -> the GTFS station name.
  static const Map<String, String> _aliases = {
    'kuala lumpur sentral': 'kl sentral',
    'kuala lumpur': 'kl sentral',
    'johor bahru sentral': 'jb sentral',
    'johor bahru': 'jb sentral',
    'woodlands': 'woodlands ciq',
    'tanjung malim': 'tanjong malim',
    'tampin': 'pulau sebang tampin',
    'pulau sebang': 'pulau sebang tampin',
    'kota bharu': 'kota baharu',
    'alor star': 'alor setar',
    'georgetown': 'butterworth',
    'penang sentral': 'butterworth',
    'penang': 'butterworth',
    'seremban 2': 'seremban',
  };

  static String _normalize(String value) {
    final cleaned = value.toLowerCase().replaceAll(RegExp(r'[^a-z0-9]+'), ' ');
    return cleaned
        .split(' ')
        .where((w) => w.isNotEmpty && !_noiseWords.contains(w))
        .join(' ');
  }

  /// Index of the GTFS station that best matches free-text [location]
  /// (e.g. "KL Sentral", "Ipoh Railway Station"), or null.
  int? resolveStation(String location) {
    final loc = ' ${_normalize(location)} ';
    if (loc.trim().isEmpty) return null;

    int? best;
    var bestLen = 0;

    // Aliases first so "Kuala Lumpur" means KL Sentral rather than the old
    // Kuala Lumpur Komuter stop; ties go to the alias.
    _aliases.forEach((phrase, target) {
      if (loc.contains(' $phrase ') && phrase.length >= bestLen) {
        final idx = _stopIndexByName[target];
        if (idx != null) {
          best = idx;
          bestLen = phrase.length;
        }
      }
    });

    _stopIndexByName.forEach((name, idx) {
      if (name.isNotEmpty && loc.contains(' $name ') && name.length > bestLen) {
        best = idx;
        bestLen = name.length;
      }
    });
    return best;
  }

  // ───────────────────────── Queries ─────────────────────────

  bool _runsOn(String serviceId, DateTime date) {
    final key = '$serviceId|${_iso(date)}';
    final exception = _exceptions[key];
    if (exception == 1) return true; // added
    if (exception == 2) return false; // removed
    final week = _services[serviceId];
    if (week == null) return false;
    return week[date.weekday - 1] == 1;
  }

  static String _iso(DateTime d) =>
      '${d.year.toString().padLeft(4, '0')}-'
      '${d.month.toString().padLeft(2, '0')}-'
      '${d.day.toString().padLeft(2, '0')}';

  /// Every train from [from] to [to] (free-text station names) running on
  /// [date], earliest first. Empty if a station is unknown or there is no
  /// direct train.
  List<TrainDeparture> departures({
    required String from,
    required String to,
    required DateTime date,
  }) {
    final a = resolveStation(from);
    final b = resolveStation(to);
    if (a == null || b == null || a == b) return const [];

    final result = <TrainDeparture>[];
    final day = DateTime(date.year, date.month, date.day);
    for (final trip in _trips) {
      final leg = trip.leg(a, b);
      if (leg == null) continue;

      // A train that leaves after midnight belongs to the previous service day.
      final serviceDay = day.subtract(Duration(days: leg.depart ~/ 1440));
      if (!_runsOn(trip.serviceId, serviceDay)) continue;

      result.add(
        TrainDeparture(
          routeId: trip.routeId,
          routeLabel: _routeLabel(trip.routeId),
          departMinutes: leg.depart % 1440,
          durationMinutes: leg.duration,
        ),
      );
    }
    result.sort((x, y) => x.departMinutes.compareTo(y.departMinutes));
    return result;
  }

  /// The scheduled train whose departure is closest to [timeMinutes]
  /// (minutes after midnight) on [date], or null.
  TrainDeparture? closestDeparture({
    required String from,
    required String to,
    required DateTime date,
    required int timeMinutes,
  }) {
    final all = departures(from: from, to: to, date: date);
    if (all.isEmpty) return null;
    all.sort(
      (x, y) => (x.departMinutes - timeMinutes).abs().compareTo(
        (y.departMinutes - timeMinutes).abs(),
      ),
    );
    return all.first;
  }

  /// Typical journey time (minutes) between two stations from the *fastest*
  /// service that connects them (so ETS beats a stopping Komuter), or null.
  int? typicalDurationMinutes(String from, String to) {
    final a = resolveStation(from);
    final b = resolveStation(to);
    if (a == null || b == null || a == b) return null;

    final byRoute = <String, List<int>>{};
    for (final trip in _trips) {
      final leg = trip.leg(a, b);
      if (leg != null && leg.duration > 0) {
        byRoute.putIfAbsent(trip.routeId, () => []).add(leg.duration);
      }
    }
    if (byRoute.isEmpty) return null;

    int median(List<int> v) {
      final s = [...v]..sort();
      return s[s.length ~/ 2];
    }

    return byRoute.values.map(median).reduce((x, y) => x < y ? x : y);
  }

  static String _routeLabel(String routeId) {
    switch (routeId) {
      case 'ETS':
        return 'ETS';
      case 'SH':
        return 'Intercity Shuttle';
      case 'ERT':
        return 'Ekspres Rakyat Timuran';
      case 'ST':
        return 'Shuttle Tebrau';
      case 'SS':
        return 'Komuter Shuttle Selatan';
      case 'KC05_KB18':
        return 'Komuter Seremban Line';
      case 'KA15_KD19':
        return 'Komuter Port Klang Line';
      case '100_47300':
        return 'Komuter Padang Besar Line';
      case '100_9000':
        return 'Komuter Ipoh Line';
      default:
        return routeId;
    }
  }
}

class _StopTime {
  final int stop;
  final int arrive;
  final int depart;
  const _StopTime(this.stop, this.arrive, this.depart);
}

class _Leg {
  final int depart;
  final int duration;
  const _Leg(this.depart, this.duration);
}

class _Trip {
  final String routeId;
  final String serviceId;
  final List<_StopTime> stops;
  const _Trip({
    required this.routeId,
    required this.serviceId,
    required this.stops,
  });

  /// Departure/duration for riding this trip from station [a] to [b], or null
  /// if the trip does not call at both in that order.
  _Leg? leg(int a, int b) {
    final i = stops.indexWhere((s) => s.stop == a);
    if (i < 0) return null;
    final j = stops.indexWhere((s) => s.stop == b, i + 1);
    if (j < 0) return null;
    return _Leg(stops[i].depart, stops[j].arrive - stops[i].depart);
  }
}
